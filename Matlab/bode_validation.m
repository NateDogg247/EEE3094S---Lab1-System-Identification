    omegaModel));


magnitudeFreqDB = ...
    20*log10(abs(responseFreq));


phaseFreq = ...
    rad2deg( ...
    unwrap(angle(responseFreq)));


%% ============================================================
% 25. FINAL-MODEL RESPONSE
%% ============================================================

responseFinal = squeeze( ...
    freqresp( ...
    Gfinal, ...
    omegaModel));


magnitudeFinalDB = ...
    20*log10(abs(responseFinal));


phaseFinal = ...
    rad2deg( ...
    unwrap(angle(responseFinal)));


